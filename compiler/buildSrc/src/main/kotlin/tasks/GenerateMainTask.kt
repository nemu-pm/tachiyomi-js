package tasks

import MainKtTemplate
import ResolvedSource
import SourceGenerator
import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.*
import java.io.File

/**
 * Generates the entry points for an extension build:
 *  - `keiyoushi/source/Generated.kt`, what upstream's KSP processor derives from the `@Source`
 *    class and the build.gradle.kts `source {}` specs;
 *  - `Main.kt`, the JS bridge over `Generated`.
 * Configuration-cache compatible.
 */
abstract class GenerateMainTask : DefaultTask() {

    @get:Input
    abstract val extensionPath: Property<String>

    @get:Input
    abstract val sources: ListProperty<ResolvedSource>

    @get:InputDirectory
    abstract val preprocessedDir: DirectoryProperty

    @get:InputFile
    abstract val translationsFile: RegularFileProperty

    /** `assets/` roots, in lookup order (extension first); [assetFiles] tracks their contents. */
    @get:Input
    abstract val assetDirs: ListProperty<String>

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val assetFiles: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val outDir = outputDir.get().asFile
        outDir.deleteRecursively()
        outDir.mkdirs()

        val preprocessed = preprocessedDir.get().asFile
        val extensionDir = File(preprocessed, "eu/kanade/tachiyomi/extension")
        val cls = SourceGenerator.findSourceClass(extensionDir, preprocessed)
        if (cls.root != "KeiSource") {
            println("  WARNING: ${cls.className} does not derive from KeiSource (root: ${cls.root}); filterFetchHint not generated")
        }
        val translations = SourceGenerator.Translations.load(translationsFile.get().asFile)
        val generated = SourceGenerator.generate(cls, sources.get(), translations)
        File(outDir, "keiyoushi/source/Generated.kt").apply { parentFile.mkdirs() }.writeText(generated)

        File(outDir, "Main.kt").writeText(MainKtTemplate.generate())
        File(outDir, "keiyoushi/source/Assets.kt").writeText(generateAssets())
    }

    /**
     * `registerAssets()`, filling the shim's ResourceRegistry with every file under the assets
     * roots as `assets/<relative path>`, the classpath name `javaClass.getResource("/assets/x")`
     * and lib:i18n ask for. Contents are base64 so no escaping is needed in the literal.
     */
    private fun generateAssets(): String {
        val out = StringBuilder()
        out.appendLine("// Generated by tachiyomi-js GenerateMainTask: the extension's assets/ folder(s).")
        out.appendLine("package keiyoushi.source")
        out.appendLine()
        out.appendLine("import tachiyomi.shim.ResourceRegistry")
        out.appendLine()
        out.appendLine("internal fun registerAssets() {")
        val seen = mutableSetOf<String>()
        for (root in assetDirs.get().map { File(it) }) {
            for (file in root.walk().filter { it.isFile }.sortedBy { it.path }) {
                val rel = file.relativeTo(root).path.replace(File.separator, "/")
                if (!seen.add(rel)) continue
                val b64 = java.util.Base64.getEncoder().encodeToString(file.readBytes())
                out.appendLine("    ResourceRegistry.registerBase64(\"assets/$rel\", \"$b64\")")
            }
        }
        out.appendLine("}")
        return out.toString()
    }
}
